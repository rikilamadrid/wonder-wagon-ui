const headers = { "user-agent": "wonder-wagon-catalog-evidence" };
if (process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

async function json(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.json();
}
async function text(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.text();
}
const gh = (repo, path) => json(`https://api.github.com/repos/${OWNER}/${repo}/${path}`);
const raw = (repo, commit, file) =>
  text(`https://raw.githubusercontent.com/${OWNER}/${repo}/${commit}/${file}`);
const blob = (repo, commit, file) => `https://github.com/${OWNER}/${repo}/blob/${commit}/${file}`;

async function tagCommit(repo, tag) {
  let object = (await gh(repo, `git/ref/tags/${encodeURIComponent(tag)}`)).object;
  while (object.type === "tag") object = (await gh(repo, `git/tags/${object.sha}`)).object;
  return object.sha;
}

async function provenance(pkg, version) {
  const response = await fetch(`${REGISTRY}/-/npm/v1/attestations/${pkg}@${version}`, { headers });
  if (response.status === 404) return { status: "none" };
  if (!response.ok) throw new Error(`${response.status} attestations ${pkg}@${version}`);
  const { attestations } = await response.json();
  const slsa = attestations.find((a) => a.predicateType.startsWith("https://slsa.dev/provenance/"));
  if (!slsa) return { status: "none" };
  const statement = JSON.parse(Buffer.from(slsa.bundle.dsseEnvelope.payload, "base64").toString());
  const build = statement.predicate.buildDefinition;
  const source = build.resolvedDependencies.find((d) => d.digest?.gitCommit);
  return {
    status: "attested",
    predicateType: slsa.predicateType,
    builder: statement.predicate.runDetails.builder.id,
    workflow: build.externalParameters.workflow.path,
    workflowRef: build.externalParameters.workflow.ref,
    sourceCommit: source.digest.gitCommit,
  };
}

async function measure(product, commit) {
  const out = [];
  for (const m of product.measure) {
    const body = await raw(product.repo, commit, m.file);
    const entry = { file: m.file, about: m.about, url: blob(product.repo, commit, m.file) };
    if (m.count === "--ww-declarations")
      entry.value = (body.match(/--ww-[a-z0-9-]+\s*:/g) ?? []).length;
    if (m.count === "--ww-references") entry.value = (body.match(/--ww-[a-z0-9-]+/g) ?? []).length;
    if (m.count === "var-split") {
      entry.value = {
        product: (body.match(/var\(--lk-/g) ?? []).length,
        family: (body.match(/var\(--ww-/g) ?? []).length,
      };
    }
    if (m.count === "generated")
      entry.value = body.startsWith("// GENERATED by wonder-wagon-ui/cli");
    if (m.count === "generated-theme") {
      const match = body.match(/wonder-wagon-ui (\d+\.\d+\.\d+), (\w+) theme/);
      entry.value = match ? { generator: match[1], theme: match[2] } : false;
    }
    out.push(entry);
  }
  return out;
}

async function generatorPin(product, commit) {
  if (product.generator.self) return { self: true };
  const manifest = JSON.parse(await raw(product.repo, commit, product.generator.file));
  const pin =
    manifest.devDependencies?.["wonder-wagon-ui"] ?? manifest.dependencies?.["wonder-wagon-ui"];
  return {
    version: pin ?? null,
    file: product.generator.file,
    url: blob(product.repo, commit, product.generator.file),
  };
}

async function describe(product) {
  const packument = await json(`${REGISTRY}/${product.package}`);
  const published = packument.versions[product.version];
  if (!published) throw new Error(`${product.package}@${product.version} is not on the registry`);
  const commit = await tagCommit(product.repo, product.tag);
  const release = await gh(product.repo, `releases/tags/${encodeURIComponent(product.tag)}`);
  const attested = await provenance(product.package, product.version);
  if (attested.status === "attested" && attested.sourceCommit !== commit) {
    throw new Error(
      `${product.package}: attested commit ${attested.sourceCommit} is not tag ${product.tag} (${commit})`,
    );
  }
  if (published.gitHead && published.gitHead !== commit) {
    throw new Error(
      `${product.package}: gitHead ${published.gitHead} is not tag ${product.tag} (${commit})`,
    );
  }
  const provenanceRecord =
    attested.status === "attested"
      ? {
          ...attested,
          source: `${REGISTRY}/-/npm/v1/attestations/${product.package}@${product.version}`,
        }
      : {
          status: "none",
          note:
            product.provenanceNote?.text ?? "No provenance attestation exists for this version.",
          source: product.provenanceNote
            ? blob(product.repo, commit, product.provenanceNote.source)
            : `${REGISTRY}/-/npm/v1/attestations/${product.package}@${product.version}`,
        };
  return {
    id: product.id,
    name: product.name,
    serial: product.serial,
    role: product.role,
    package: product.package,
    version: product.version,
    npm: `https://www.npmjs.com/package/${product.package}/v/${product.version}`,
    publishedAt: packument.time[product.version],
    integrity: published.dist.integrity,
    gitHead: published.gitHead ?? null,
    release: { tag: product.tag, commit, url: release.html_url, publishedAt: release.published_at },
    provenance: provenanceRecord,
    generator: await generatorPin(product, commit),
    integration: { ...product.integration, measured: await measure(product, commit) },
    repository: `https://github.com/${OWNER}/${product.repo}`,
    site: product.site,
  };
}

const evidence = {
  about:
    "Release evidence for the public Wonder Wagon family, read from npm and GitHub at pinned versions and commits by apps/docs/scripts/evidence.mjs. Curated claims (roles, integration depth in words) are written in that script; every number beside them is measured.",
  products: [],
  drafts: DRAFTS,
};
for (const product of PRODUCTS) evidence.products.push(await describe(product));

const rendered = `${JSON.stringify(evidence, null, 2)}\n`;
if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== rendered) {
    console.error(
      "evidence: src/evidence/evidence.json is stale; run node apps/docs/scripts/evidence.mjs",
    );
    process.exit(1);
  }
  console.log(`evidence: ${evidence.products.length} packages match the public record`);
} else {
  writeFileSync(OUT, rendered);
  console.log(`evidence: wrote ${evidence.products.length} packages`);
}
